"""Alembic environment configuration for Single-Instructor LMS.

Architecture Reference: docs/backend/04-DATABASE-ARCHITECTURE.md
Connects Alembic migration pipeline to:
1. Centralized Pydantic Settings (get_settings().DATABASE_URL).
2. SQLAlchemy 2.0 Base metadata (Base.metadata) with PostgreSQL naming conventions.
3. Offline SQL generation support (alembic upgrade head --sql).
4. Online transactional migration execution using NullPool to prevent connection leaks.
5. Dynamic SQLite batch mode for isolated test execution.
"""

from logging.config import fileConfig
from pathlib import Path
import sys

from alembic import context
from sqlalchemy import pool

# Ensure the backend directory is in sys.path so 'app.*' imports resolve cleanly
backend_dir = Path(__file__).resolve().parent.parent
if str(backend_dir) not in sys.path:
    sys.path.insert(0, str(backend_dir))

from app.core.config import get_settings
from app.core.database import create_db_engine
from app.models import Base

# Alembic Config object, which provides access to the values within alembic.ini.
# Handled gracefully if imported directly in tests outside of Alembic migration execution.
try:
    config = context.config
except AttributeError:
    config = None

# Interpret the config file for Python logging if present
if config is not None and config.config_file_name is not None:
    fileConfig(config.config_file_name)

# Wire the declarative Base metadata for autogenerate discovery
target_metadata = Base.metadata


def include_object(object, name, type_, reflected, compare_to):
    """Filter out test fixtures and temporary tables from migration autogeneration.

    Prevents dynamically declared test models (originating from test suites under 'tests.*'
    or prefixed with 'test_dummy_') from polluting autogenerated migrations when
    running within test runners.

    Crucially, legitimate production domain tables (such as student assessment tables
    'test_attempts', 'test_questions', or 'test_series' originating from 'app.models.*')
    are never excluded from Alembic autogeneration.
    """
    table_name = name if type_ == "table" else getattr(getattr(object, "table", None), "name", None)

    if table_name:
        # Exclude tables explicitly designated as test fixtures
        if table_name.startswith("test_dummy_") or table_name.startswith("test_constrained_"):
            return False

        # Exclude models declared inside test suites (e.g. tests.unit.*)
        for mapper in Base.registry.mappers:
            if mapper.local_table.name == table_name:
                mod = mapper.class_.__module__
                if mod.startswith("tests.") or mod.startswith("test_"):
                    return False

    return True


def get_database_url() -> str:
    """Retrieve the active database URL.
    
    Priority:
    1. Alembic runtime -x command-line argument (e.g. alembic -x url=sqlite:///:memory: ...).
    2. Explicit configuration option in alembic.ini (sqlalchemy.url).
    3. Centralized Pydantic Settings (app.core.config.get_settings().DATABASE_URL).
    """
    if config is not None:
        try:
            x_args = context.get_x_argument(as_dictionary=True)
            if "url" in x_args and x_args["url"].strip():
                return x_args["url"].strip()
        except Exception:
            pass

        cmd_url = config.get_main_option("sqlalchemy.url")
        if cmd_url and cmd_url.strip():
            return cmd_url.strip()

    settings_url = get_settings().DATABASE_URL
    if not settings_url or not settings_url.strip():
        raise ValueError("DATABASE_URL is not configured in Pydantic Settings or environment.")
    return settings_url.strip()


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode.

    Configures the context with just a URL and not an active Engine.
    Calls to context.execute() emit the generated SQL directly to the script output,
    enabling dry-run SQL inspection before applying migrations to production.
    """
    url = get_database_url()
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
        include_object=include_object,
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode.

    Creates a dedicated SQLAlchemy Engine with NullPool to prevent idle connection
    leakage during migration execution, then executes migrations within an explicit
    database transaction.
    """
    url = get_database_url()

    # Use NullPool during migrations so connections close immediately upon completion
    connectable = create_db_engine(
        database_url=url,
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            compare_type=True,
            compare_server_default=True,
            render_as_batch=connection.dialect.name == "sqlite",
            include_object=include_object,
        )

        with context.begin_transaction():
            context.run_migrations()

    connectable.dispose()


if config is not None:
    if context.is_offline_mode():
        run_migrations_offline()
    else:
        run_migrations_online()
