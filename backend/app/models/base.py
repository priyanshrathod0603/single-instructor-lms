"""SQLAlchemy 2.0 DeclarativeBase, UUID primary key mixin, and UTC timestamp mixin.

Follows the database architecture specification in docs/backend/04-DATABASE-ARCHITECTURE.md.
All persistent models enforce:
1. UUIDv4 primary keys with server_default=text("gen_random_uuid()") and default=uuid.uuid4.
2. TIMESTAMPTZ timestamps with server_default=func.now() and default=utc_now.
3. Standardized naming conventions for primary keys, foreign keys, unique constraints, and indexes.
4. Defense-in-depth serializer utilities automatically excluding sensitive fields (hashes, tokens, secrets).
5. Safe debugging string representations strictly restricted to class name and primary key.
"""

from collections.abc import Set
from datetime import datetime, timezone
from typing import Any, ClassVar, Optional
import uuid

from sqlalchemy import DateTime, MetaData, TypeDecorator, Uuid, func, inspect, text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Consistent constraint naming conventions across PostgreSQL and Alembic migrations.
# Eliminates unpredictable autogenerated constraint names in database DDL.
POSTGRES_NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# Universally sensitive attribute names automatically excluded from serialization
# to prevent accidental exposure of credentials in logs, tracebacks, or API payloads.
DEFAULT_SENSITIVE_FIELDS: frozenset[str] = frozenset({
    "password_hash",
    "token_hash",
    "session_token_hash",
    "secret_key",
    "secret",
    "private_key",
    "webhook_secret",
    "access_token",
    "refresh_token",
})


def utc_now(context: Optional[Any] = None) -> datetime:
    """Return the current timezone-aware UTC datetime.
    
    Accepts an optional context parameter so it can be passed directly as a
    SQLAlchemy column default or onupdate callable.
    """
    return datetime.now(timezone.utc)


class UTCDateTime(TypeDecorator):
    """Platform-independent timezone-aware UTC DateTime.
    
    Compiles to PostgreSQL `TIMESTAMP WITH TIME ZONE` (TIMESTAMPTZ) in DDL.
    Guarantees that all retrieved datetime objects carry `tzinfo=timezone.utc`,
    preventing timezone-naive datetime bugs even when executing against SQLite
    in local or test environments.
    """

    impl = DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(self, value: Optional[datetime], dialect: Any) -> Optional[datetime]:
        """Normalize outgoing datetimes to UTC before storing in the database."""
        if value is not None:
            if not isinstance(value, datetime):
                raise TypeError(f"Expected datetime.datetime, got {type(value).__name__}")
            if value.tzinfo is None:
                # If naive, assume UTC
                value = value.replace(tzinfo=timezone.utc)
            else:
                value = value.astimezone(timezone.utc)
        return value

    def process_result_value(self, value: Optional[datetime], dialect: Any) -> Optional[datetime]:
        """Ensure incoming datetimes from the database carry UTC tzinfo."""
        if value is not None:
            if value.tzinfo is None:
                value = value.replace(tzinfo=timezone.utc)
            else:
                value = value.astimezone(timezone.utc)
        return value


class Base(DeclarativeBase):
    """Base declarative class for all SQLAlchemy 2.0 ORM models.
    
    Equipped with standard constraint naming conventions, defense-in-depth dictionary
    serialization, and structured string representations.
    """

    metadata = MetaData(naming_convention=POSTGRES_NAMING_CONVENTION)

    # Optional model-level sensitive fields to exclude from serialization
    __sensitive_fields__: ClassVar[frozenset[str]] = frozenset()

    def to_dict(
        self,
        exclude: Optional[Set[str]] = None,
        include_sensitive: bool = False,
    ) -> dict[str, Any]:
        """Convert ORM model attributes into a JSON-serializable dictionary.
        
        Security Invariants:
        1. Universally sensitive fields (password_hash, token_hash, etc.) are excluded
           by default unless include_sensitive=True is explicitly specified.
        2. Model-declared `__sensitive_fields__` are automatically merged into exclusion.
        3. Callers can supply additional custom attributes via the `exclude` set.
        
        Args:
            exclude: Optional set of attribute names to omit from serialization.
            include_sensitive: If True, bypasses automatic exclusion of sensitive fields.
            
        Returns:
            Dictionary containing column names and formatted values (UUIDs and
            datetimes converted to ISO-8601 strings).
        """
        exclude_set = set(exclude or set())

        # Enforce automatic exclusion of sensitive fields unless explicitly opted out
        if not include_sensitive:
            model_sensitive = getattr(self.__class__, "__sensitive_fields__", frozenset())
            exclude_set.update(DEFAULT_SENSITIVE_FIELDS)
            exclude_set.update(model_sensitive)

        mapper = inspect(self.__class__)
        result: dict[str, Any] = {}

        for column in mapper.column_attrs:
            key = column.key
            if key in exclude_set:
                continue
            value = getattr(self, key)
            if isinstance(value, uuid.UUID):
                result[key] = str(value)
            elif isinstance(value, datetime):
                # Ensure UTC ISO-8601 formatting
                result[key] = value.isoformat()
            else:
                result[key] = value

        return result

    def __repr__(self) -> str:
        """Provide a clean string representation for logging and debugging.
        
        Strictly outputs the class name and primary key (if available).
        Never prints column values or dictionary attributes, preventing accidental
        leakage of credentials into log streams or exception tracebacks.
        """
        primary_key_val = getattr(self, "id", None)
        if primary_key_val is not None:
            return f"<{self.__class__.__name__} id={primary_key_val}>"
        return f"<{self.__class__.__name__}>"


class UUIDPrimaryKeyMixin:
    """Mixin that injects a UUIDv4 primary key column.
    
    Uses `gen_random_uuid()` as the database server default (PostgreSQL 13+)
    and `uuid.uuid4` as the client-side default.
    Ensures that offline or client-side object creation assigns a valid UUID
    even before the row is flushed to the database.
    """

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
        nullable=False,
        sort_order=-100,  # Guarantees the primary key column appears first
    )


class TimestampMixin:
    """Mixin that injects timezone-aware UTC created_at and updated_at columns.
    
    Uses PostgreSQL `TIMESTAMPTZ` (TIMESTAMP WITH TIME ZONE) via UTCDateTime with
    server_default=func.now() and client-side default=utc_now.
    The updated_at column automatically updates on every ORM modification.
    """

    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime,
        default=utc_now,
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        UTCDateTime,
        default=utc_now,
        onupdate=utc_now,
        server_default=func.now(),
        nullable=False,
    )
